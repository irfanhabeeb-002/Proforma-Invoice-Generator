-- 2. Sequences Table (Per-Year Atomic Counters)
-- CRITICAL: Preserves existing table and sequence counters (NEVER drop or reset)
CREATE TABLE IF NOT EXISTS public.pi_sequences (
    year INT PRIMARY KEY,
    last_number INT NOT NULL DEFAULT 0
);

-- 3. Recreate Empty PI Records & Download Events Tables
-- Safely drops zero-row tables to establish standardized schema cleanly
DROP TABLE IF EXISTS public.pi_download_events CASCADE;
DROP TABLE IF EXISTS public.pi_records CASCADE;

CREATE TABLE public.pi_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id UUID NOT NULL UNIQUE,                       -- Idempotency key from draft lifecycle
    pi_number TEXT NOT NULL UNIQUE,                         -- Format: PI-YYYY-NNN (e.g. PI-2026-001)
    year INT NOT NULL,
    sequence_number INT NOT NULL,
    customer_name TEXT NOT NULL,
    created_by_employee TEXT NOT NULL,
    pi_date DATE NOT NULL,
    subtotal NUMERIC(14, 2) NOT NULL DEFAULT 0.00,
    tax_total NUMERIC(14, 2) NOT NULL DEFAULT 0.00,
    grand_total NUMERIC(14, 2) NOT NULL DEFAULT 0.00,
    items JSONB NOT NULL DEFAULT '[]'::jsonb,              -- Complete line items for exact PDF regeneration
    filename TEXT NOT NULL,                                -- Format: PI-YYYY-NNN_CUSTOMER_NAME.pdf
    status TEXT NOT NULL DEFAULT 'Finalized',              -- 'Finalized', 'Download initiated', 'Void'
    latest_downloaded_by TEXT,
    download_initiated_at TIMESTAMPTZ,
    download_count INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Optimized indexes for history filtering and search
CREATE INDEX idx_pi_records_year ON public.pi_records(year);
CREATE INDEX idx_pi_records_pi_date ON public.pi_records(pi_date);
CREATE INDEX idx_pi_records_created_by ON public.pi_records(created_by_employee);
CREATE INDEX idx_pi_records_customer ON public.pi_records(customer_name);
CREATE INDEX idx_pi_records_request_id ON public.pi_records(request_id);

-- 4. Download Events Audit Table
CREATE TABLE public.pi_download_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pi_number TEXT NOT NULL REFERENCES public.pi_records(pi_number) ON DELETE CASCADE,
    downloaded_by_employee TEXT NOT NULL,
    download_initiated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_pi_download_events_pi_number ON public.pi_download_events(pi_number);

-- ==============================================================================
-- 5. Drop Obsolete Overloads of RPC Functions
-- Ensures clean state before creating hardened versions
-- ==============================================================================
DO $$
DECLARE
    r RECORD;
BEGIN
    FOR r IN (
        SELECT p.proname, pg_catalog.pg_get_function_identity_arguments(p.oid) AS args
        FROM pg_catalog.pg_proc p
        JOIN pg_catalog.pg_namespace n ON n.oid = p.pronamespace
        WHERE n.nspname = 'public' AND p.proname IN ('allocate_pi', 'record_pi_download')
    ) LOOP
        EXECUTE 'DROP FUNCTION IF EXISTS public.' || quote_ident(r.proname) || '(' || r.args || ') CASCADE;';
    END LOOP;
END $$;

-- ==============================================================================
-- 6. Stored Procedure: allocate_pi()
-- Requirements:
-- - SET search_path = '' (fully schema-qualified objects)
-- - PostgreSQL advisory transaction locking on p_request_id
-- - Complete Idempotency: compares customer_name, creator, date, year, subtotal,
--   tax_total, grand_total, items JSONB.
-- - Rejects reuse of request UUID with different invoice details.
-- - Validates that creator is an active employee.
-- - Atomic sequence allocation and record insertion in one transaction.
-- - Generates PI-YYYY-NNN and filename inside PostgreSQL.
-- - Execution granted EXCLUSIVELY to service_role.
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.allocate_pi(
    p_request_id uuid,
    p_customer_name text,
    p_created_by_employee text,
    p_pi_date date DEFAULT (pg_catalog.now())::date,
    p_subtotal numeric DEFAULT 0.00,
    p_tax_total numeric DEFAULT 0.00,
    p_grand_total numeric DEFAULT 0.00,
    p_items jsonb DEFAULT '[]'::jsonb,
    p_year integer DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_existing public.pi_records%ROWTYPE;
    v_year integer;
    v_next_val integer;
    v_pi_number text;
    v_clean_cust text;
    v_filename text;
    v_record public.pi_records%ROWTYPE;
BEGIN
    -- 1. Concurrency Protection: Acquire PostgreSQL advisory transaction lock
    PERFORM pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext('allocate_pi_' || p_request_id::text));

    -- 2. Determine target year
    IF p_year IS NOT NULL AND p_year > 2000 THEN
        v_year := p_year;
    ELSE
        v_year := pg_catalog.date_part('year', p_pi_date)::integer;
    END IF;

    -- 3. Complete Idempotency Check
    SELECT * INTO v_existing FROM public.pi_records WHERE request_id = p_request_id;
    IF FOUND THEN
        -- Compare all invoice-defining details
        IF pg_catalog.btrim(v_existing.customer_name) != pg_catalog.btrim(p_customer_name) OR
           pg_catalog.btrim(v_existing.created_by_employee) != pg_catalog.btrim(p_created_by_employee) OR
           v_existing.pi_date != p_pi_date OR
           v_existing.year != v_year OR
           pg_catalog.abs(v_existing.subtotal - p_subtotal) > 0.001 OR
           pg_catalog.abs(v_existing.tax_total - p_tax_total) > 0.001 OR
           pg_catalog.abs(v_existing.grand_total - p_grand_total) > 0.001 OR
           v_existing.items::jsonb != p_items::jsonb THEN
            RAISE EXCEPTION 'Request UUID % has already been used for a different invoice with conflicting details.', p_request_id;
        END IF;

        -- Return existing identical record safely
        RETURN pg_catalog.to_jsonb(v_existing);
    END IF;

    -- 4. Validate that the creator employee is active
    IF NOT EXISTS (
        SELECT 1 FROM public.pi_employees 
        WHERE name = pg_catalog.btrim(p_created_by_employee) AND is_active = TRUE
    ) THEN
        RAISE EXCEPTION 'Employee "%" is not an active employee.', p_created_by_employee;
    END IF;

    -- 5. Atomic sequence allocation within the transaction
    INSERT INTO public.pi_sequences (year, last_number)
    VALUES (v_year, 1)
    ON CONFLICT (year)
    DO UPDATE SET last_number = public.pi_sequences.last_number + 1
    RETURNING last_number INTO v_next_val;

    -- 6. Format PI Number: PI-YYYY-NNN (e.g. PI-2026-001)
    v_pi_number := 'PI-' || v_year::text || '-' || pg_catalog.lpad(v_next_val::text, 3, '0');

    -- 7. Format clean customer name for filename (uppercase alphanumeric & underscores)
    v_clean_cust := pg_catalog.regexp_replace(pg_catalog.upper(pg_catalog.btrim(p_customer_name)), '[^A-Z0-9_-]+', '_', 'g');
    v_clean_cust := pg_catalog.regexp_replace(v_clean_cust, '_+', '_', 'g');
    v_clean_cust := pg_catalog.btrim(v_clean_cust, '_');
    IF v_clean_cust = '' THEN
        v_clean_cust := 'CUSTOMER';
    END IF;

    -- Format Filename: PI-YYYY-NNN_CUSTOMER_NAME.pdf
    v_filename := v_pi_number || '_' || v_clean_cust || '.pdf';

    -- 8. Insert new PI Record atomically
    INSERT INTO public.pi_records (
        request_id,
        pi_number,
        year,
        sequence_number,
        customer_name,
        created_by_employee,
        pi_date,
        subtotal,
        tax_total,
        grand_total,
        items,
        filename,
        status
    )
    VALUES (
        p_request_id,
        v_pi_number,
        v_year,
        v_next_val,
        pg_catalog.btrim(p_customer_name),
        pg_catalog.btrim(p_created_by_employee),
        p_pi_date,
        p_subtotal,
        p_tax_total,
        p_grand_total,
        p_items,
        v_filename,
        'Finalized'
    )
    RETURNING * INTO v_record;

    RETURN pg_catalog.to_jsonb(v_record);
END;
$$;

-- ==============================================================================
-- 7. Stored Procedure: record_pi_download()
-- Requirements:
-- - SET search_path = '' (fully schema-qualified objects)
-- - Validates that PI exists and prevents download of voided records
-- - Validates that downloading employee is active
-- - Inserts one audit event per initiation into public.pi_download_events
-- - Updates latest downloader, timestamp, and increments download_count
-- - Status becomes 'Download initiated'
-- - Execution granted EXCLUSIVELY to service_role
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.record_pi_download(
    p_pi_number text,
    p_downloaded_by_employee text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_now timestamptz := pg_catalog.now();
    v_record public.pi_records%ROWTYPE;
BEGIN
    -- 1. Validate PI Record existence
    SELECT * INTO v_record FROM public.pi_records WHERE pi_number = p_pi_number;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'PI record "%" does not exist.', p_pi_number;
    END IF;

    -- 2. Prevent downloads of voided records
    IF v_record.status ILIKE 'void%' THEN
        RAISE EXCEPTION 'Cannot download voided PI record "%".', p_pi_number;
    END IF;

    -- 3. Validate downloader employee is active
    IF NOT EXISTS (
        SELECT 1 FROM public.pi_employees 
        WHERE name = pg_catalog.btrim(p_downloaded_by_employee) AND is_active = TRUE
    ) THEN
        RAISE EXCEPTION 'Employee "%" is not an active employee.', p_downloaded_by_employee;
    END IF;

    -- 4. Record download event in audit log
    INSERT INTO public.pi_download_events (
        pi_number,
        downloaded_by_employee,
        download_initiated_at
    )
    VALUES (
        p_pi_number,
        pg_catalog.btrim(p_downloaded_by_employee),
        v_now
    );

    -- 5. Update latest downloader, count, and status on pi_records
    UPDATE public.pi_records
    SET latest_downloaded_by = pg_catalog.btrim(p_downloaded_by_employee),
        download_initiated_at = v_now,
        download_count = download_count + 1,
        status = 'Download initiated',
        updated_at = v_now
    WHERE pi_number = p_pi_number
    RETURNING * INTO v_record;

    RETURN pg_catalog.to_jsonb(v_record);
END;
$$;

