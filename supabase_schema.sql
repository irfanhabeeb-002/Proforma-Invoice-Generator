-- 1. Standardize and Migrate Employees Table
-- Safe adaptation: renames legacy columns (employee_name -> name, active -> is_active)
-- while preserving all existing employee rows.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.tables 
        WHERE table_schema = 'public' AND table_name = 'pi_employees'
    ) THEN
        CREATE TABLE public.pi_employees (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL UNIQUE,
            is_active BOOLEAN NOT NULL DEFAULT TRUE,
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        );
    ELSE
        -- Rename employee_name -> name if present
        IF EXISTS (
            SELECT 1 FROM information_schema.columns 
            WHERE table_schema = 'public' AND table_name = 'pi_employees' AND column_name = 'employee_name'
        ) THEN
            ALTER TABLE public.pi_employees RENAME COLUMN employee_name TO name;
        END IF;

        -- Rename active -> is_active if present
        IF EXISTS (
            SELECT 1 FROM information_schema.columns 
            WHERE table_schema = 'public' AND table_name = 'pi_employees' AND column_name = 'active'
        ) THEN
            ALTER TABLE public.pi_employees RENAME COLUMN active TO is_active;
        END IF;

        -- Ensure NOT NULL constraint on name
        ALTER TABLE public.pi_employees ALTER COLUMN name SET NOT NULL;

        -- Ensure unique constraint on name
        IF NOT EXISTS (
            SELECT 1 FROM pg_constraint WHERE conname = 'pi_employees_name_key'
        ) THEN
            ALTER TABLE public.pi_employees ADD CONSTRAINT pi_employees_name_key UNIQUE (name);
        END IF;

        -- Ensure default TRUE for is_active
        ALTER TABLE public.pi_employees ALTER COLUMN is_active SET DEFAULT TRUE;
    END IF;
END $$;

