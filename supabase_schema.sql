REVOKE ALL ON FUNCTION public.allocate_pi(uuid, text, text, date, numeric, numeric, numeric, jsonb, integer) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.record_pi_download(text, text) FROM PUBLIC, anon, authenticated;

GRANT EXECUTE ON FUNCTION public.allocate_pi(uuid, text, text, date, numeric, numeric, numeric, jsonb, integer) TO service_role;
GRANT EXECUTE ON FUNCTION public.record_pi_download(text, text) TO service_role;

